package com.xique.assistant;

import com.getcapacitor.JSObject;
import com.getcapacitor.PluginCall;

import org.json.JSONArray;
import org.json.JSONObject;

import java.util.Arrays;
import java.util.HashSet;
import java.util.Set;

/** Strict argument validation for the two local-school Capacitor plugins. */
final class BridgeArgs {
    private BridgeArgs() {}

    static JSObject exact(PluginCall call, String... keys) throws org.json.JSONException {
        JSObject data = call.getData();
        if (data == null || data.length() != keys.length) throw new IllegalArgumentException();
        Set<String> allowed = new HashSet<>(Arrays.asList(keys));
        for (String key : allowed) {
            Object value = data.get(key);
            if (value == null || value == JSONObject.NULL) throw new IllegalArgumentException();
        }
        java.util.Iterator<String> names = data.keys();
        while (names.hasNext()) {
            if (!allowed.contains(names.next())) throw new IllegalArgumentException();
        }
        return data;
    }

    static String text(JSObject data, String key, int max) throws org.json.JSONException {
        Object value = data.get(key);
        if (!(value instanceof String)) throw new IllegalArgumentException();
        String text = (String) value;
        if (text.isEmpty() || text.length() > max) throw new IllegalArgumentException();
        return text;
    }

    /** Workspace ids are generated by LocalDb.newUuid(); reject free-form ids. */
    static String uuid(JSObject data, String key) throws org.json.JSONException {
        String text = text(data, key, 36);
        if (!text.matches("[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}")) {
            throw new IllegalArgumentException();
        }
        return text;
    }

    /** JS-safe non-negative integer (2^53-1 ceiling). */
    static long integer(JSObject data, String key) throws org.json.JSONException {
        Object value = data.get(key);
        if (!(value instanceof Number)) throw new IllegalArgumentException();
        Number number = (Number) value;
        double asDouble = number.doubleValue();
        long asLong = number.longValue();
        if (asDouble != (double) asLong || asLong < 0 || asLong > 9007199254740991L) {
            throw new IllegalArgumentException();
        }
        return asLong;
    }

    static JSONArray stringArray(JSObject data, String key) throws org.json.JSONException {
        Object value = data.get(key);
        if (!(value instanceof JSONArray)) throw new IllegalArgumentException();
        JSONArray array = (JSONArray) value;
        for (int i = 0; i < array.length(); i++) {
            if (!(array.opt(i) instanceof String)) throw new IllegalArgumentException();
        }
        return array;
    }

    static JSObject object(JSObject data, String key) throws org.json.JSONException {
        Object value = data.get(key);
        if (!(value instanceof JSONObject)) throw new IllegalArgumentException();
        return new JSObject(value.toString());
    }

    static void reject(PluginCall call, Exception error) {
        if (error instanceof com.xique.assistant.henu.ops.HenuError) {
            com.xique.assistant.henu.ops.HenuError henu = (com.xique.assistant.henu.ops.HenuError) error;
            call.reject(henu.getMessage(), henu.code);
        } else if (error instanceof IllegalArgumentException
                || error instanceof org.json.JSONException) {
            call.reject("Invalid arguments", "INVALID_ARGUMENT");
        } else {
            call.reject("Local storage unavailable", "STORAGE_UNAVAILABLE");
        }
    }
}
